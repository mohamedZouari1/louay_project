// Search functionality
function searchLocation() {
  const searchInput = document.getElementById('searchInput').value.toLowerCase();
  const resultsContainer = document.getElementById('searchResults');

  if (!searchInput.trim()) {
    resultsContainer.innerHTML = '';
    addMarkers();
    return;
  }

  const results = campusData.features.filter(feature => {
    const name = (feature.properties.name || '').toLowerCase();
    const category = (feature.properties.category || '').toLowerCase();
    const description = (feature.properties.description || '').toLowerCase();

    return name.includes(searchInput) ||
      category.includes(searchInput) ||
      description.includes(searchInput);
  });

  displaySearchResults(results);
  addMarkers(results);
}

// Display search results
function displaySearchResults(results) {
  const resultsContainer = document.getElementById('searchResults');

  if (results.length === 0) {
    resultsContainer.innerHTML = '<p class="empty-message">No results found</p>';
    return;
  }

  resultsContainer.innerHTML = results.map(feature => `
        <div class="search-result-item" onclick="zoomToLocation(${feature.geometry.coordinates[1]}, ${feature.geometry.coordinates[0]}, '${feature.properties.name.replace(/'/g, "\\'")}')">
            <div class="result-name">${feature.properties.name}</div>
            <div class="result-category">${feature.properties.category || 'General'}</div>
        </div>
    `).join('');
}

// Zoom to location
function zoomToLocation(lat, lng, name) {
  map.setView([lat, lng], 18);

  // Find the feature and show details in sidebar
  const feature = campusData.features.find(f => f.properties.name === name);
  if (feature) {
    showLocationDetails(feature);
  }
}

// Filter by category
function filterByCategory(category) {
  const filtered = campusData.features.filter(feature =>
    feature.properties.category === category
  );

  addMarkers(filtered);

  // Zoom to fit markers
  if (filtered.length > 0) {
    const bounds = L.latLngBounds(filtered.map(f => [f.geometry.coordinates[1], f.geometry.coordinates[0]]));
    map.fitBounds(bounds, { padding: [50, 50] });
  }
}

// Toggle favorite
function toggleFavorite(name, category) {
  const index = favorites.findIndex(fav => fav.name === name);

  if (index > -1) {
    favorites.splice(index, 1);
  } else {
    favorites.push({ name, category });
  }

  localStorage.setItem('campusFavorites', JSON.stringify(favorites));
  updateFavoritesList();
}

// Update favorites list
function updateFavoritesList() {
  const favoritesList = document.getElementById('favoritesList');

  if (favorites.length === 0) {
    favoritesList.innerHTML = '<p class="empty-message">No favorite places yet. Click the star icon on any location to add it to favorites!</p>';
    return;
  }

  favoritesList.innerHTML = favorites.map(fav => `
        <div class="favorite-item">
            <div class="favorite-info" onclick="findAndZoomToFavorite('${fav.name.replace(/'/g, "\\'")}')">
                <div class="favorite-name">${fav.name}</div>
                <div class="favorite-category">${fav.category}</div>
            </div>
            <div class="favorite-actions">
                <button class="favorite-btn" onclick="findAndZoomToFavorite('${fav.name.replace(/'/g, "\\'")}')">
                    <i class="fas fa-location-arrow"></i>
                </button>
                <button class="favorite-btn" onclick="toggleFavorite('${fav.name.replace(/'/g, "\\'")}', '${fav.category}')">
                    <i class="fas fa-trash"></i>
                </button>
            </div>
        </div>
    `).join('');
}

// Find and zoom to favorite
function findAndZoomToFavorite(name) {
  const feature = campusData.features.find(f => f.properties.name === name);
  if (feature) {
    zoomToLocation(
      feature.geometry.coordinates[1],
      feature.geometry.coordinates[0],
      name
    );
  }
}

// Change map layer
function changeMapLayer() {
  const layerSelect = document.getElementById('layerSelect');
  const newLayer = layerSelect.value;

  // Remove current layer
  mapLayers[currentLayer].remove();

  // Add new layer
  mapLayers[newLayer].addTo(map);
  currentLayer = newLayer;
}

// Toggle dark mode
function toggleDarkMode() {
  const isDarkMode = document.getElementById('darkModeToggle').checked;
  document.body.classList.toggle('dark-mode', isDarkMode);

  if (isDarkMode) {
    // Switch to dark map tiles
    mapLayers[currentLayer].remove();
    const darkLayer = L.tileLayer('https://{s}.basemaps.cartocdn.com/dark_all/{z}/{x}/{y}{r}.png', {
      attribution: '© OpenStreetMap © CartoDB',
      maxZoom: 19
    });
    darkLayer.addTo(map);
    mapLayers.dark = darkLayer;
    currentLayer = 'dark';
  } else {
    // Switch back to original layer
    if (mapLayers.dark) {
      mapLayers.dark.remove();
    }
    mapLayers.streets.addTo(map);
    currentLayer = 'streets';
  }
}


// Get directions
function getDirections(lat, lng) {
  const url = `https://www.google.com/maps/dir/?api=1&destination=${lat},${lng}`;
  window.open(url, '_blank');
}

